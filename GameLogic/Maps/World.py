class mapMarker:
    def __init__(self, worldMap, start):
        self.initials, self.position = "..", start
        self.rank, self.type = "world", "marker"
        self.atrb = {"base_sp": 1}
        self.lastVisited = [start,[],[],[],[],[],[]]

        self.sightMap = createSightMap(worldMap, start, self.rank)

        Select.waitPrint("World map instantiated!")


def createSightMap(worldMap, position, rank):
    sightMap = Visibility.createSightMap(worldMap, position, rank)

    for column in range(12):
        for row in range(12):
            spaceDistance = Movement.getSpaceDistance(position[0], row, position[1], column)
            if spaceDistance > 2:
                sightMap[row][column] = Visibility.unseen + worldMap[row][column][-1]

    return sightMap